/**
 * Traduz uma chave. `vars` faz interpolação de {placeholders}.
 * Se `vars.n` for diferente de 1, tenta primeiro a chave `<key>_plural`.
 */
export function t(key, vars) {
  const table = DICT[current] || DICT['pt-BR'];
  let str = key;
  if (vars && typeof vars.n === 'number' && vars.n !== 1 && table[key + '_plural']) {
    str = table[key + '_plural'];
  } else if (table[key] !== undefined) {
    str = table[key];
  } else if (DICT['pt-BR'][key] !== undefined) {
    str = DICT['pt-BR'][key];
  }
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (m, name) => (vars[name] !== undefined ? String(vars[name]) : m));
}

/** Aplica as traduções nos elementos marcados com data-i18n* do HTML. */
export function applyStaticTranslations(root) {
  const scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  scope.querySelectorAll('[data-i18n-html]').forEach((el) => {
    // Só chaves do dicionário chegam aqui — nunca conteúdo do usuário.
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  scope.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
  });
  scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.dataset.i18nTitle));
    if (el.hasAttribute('aria-label')) el.setAttribute('aria-label', t(el.dataset.i18nTitle));
  });
  scope.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
}

